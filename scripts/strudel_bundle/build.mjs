// Bundle Strudel's pattern packages and nanodirt's harness into one script for QuickJS.
// usage: node build.mjs <strudel checkout> <out file> [<third-party notices file>]
import * as esbuild from 'esbuild';
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const [root, out, notices] = process.argv.slice(2);
const here = path.dirname(fileURLToPath(import.meta.url));
const pkg = (name) => path.join(root, 'packages', name);

// fraction.js 5.2.1's float parse, one mediant step per iteration; farey.js has the reason.
const FAREY_LOOP = /\n {6}while \(B <= N && D <= N\) \{\n[\s\S]*?\n {6}\}\n(?= {6}n = BigInt\(n\) \* BigInt\(z\);)/g;
const fastFarey = {
  name: 'fast-farey',
  setup(build) {
    build.onLoad({ filter: /fraction\.js[\\/]dist[\\/]fraction\.mjs$/ }, (args) => {
      const src = fs.readFileSync(args.path, 'utf8');
      const loops = src.match(FAREY_LOOP) ?? [];
      if (loops.length !== 1 || !loops[0].includes('A += C;') || !loops[0].includes('C += A;')) {
        throw new Error(`fraction.js: expected one Farey loop, found ${loops.length}; check farey.js`);
      }
      const farey = fs.readFileSync(path.join(here, 'farey.js'), 'utf8');
      const contents = src.replace(FAREY_LOOP, '\n      [n, d] = __nanodirt_farey(p1, N);\n') + '\n' + farey;
      return { contents, loader: 'js' };
    });
  },
};
const result = await esbuild.build({
  entryPoints: [path.join(here, 'harness.mjs')],
  outfile: out,
  bundle: true,
  format: 'iife',
  platform: 'neutral',
  mainFields: ['module', 'main'],
  nodePaths: [path.join(here, 'node_modules')],
  alias: Object.fromEntries(
    ['core', 'mini', 'tonal', 'transpiler', 'edo', 'xen'].map((n) => [`@strudel/${n}`, pkg(n)]),
  ),
  define: { 'process.env.NODE_ENV': '"production"' },
  legalComments: 'inline',
  logLevel: 'warning',
  plugins: [fastFarey],
  metafile: true,
});
console.log('built', out);

// Licences of the npm packages the bundle includes, which MIT, ISC and BSD require to ship
// with it. Strudel's own packages come from the checkout and are AGPL-3.0-or-later.
if (notices) {
  const roots = new Set();
  for (const input of Object.keys(result.metafile.inputs)) {
    const m = input.match(/^(.*node_modules\/(?:@[^/]+\/)?[^/]+)\//);
    if (m) roots.add(path.resolve(m[1]));
  }
  const packages = new Map(); // name@version: nested node_modules repeat packages
  for (const dir of roots) {
    const meta = JSON.parse(fs.readFileSync(path.join(dir, 'package.json'), 'utf8'));
    packages.set(`${meta.name}@${meta.version}`, { dir, meta });
  }
  const sorted = [...packages.entries()].sort(([a], [b]) => (a < b ? -1 : 1)).map(([, p]) => p);
  const sections = sorted.map(({ dir, meta }) => {
    const file = fs.readdirSync(dir).find((f) => /^(licen[cs]e|copying)/i.test(f));
    const author = typeof meta.author === 'object' ? meta.author.name : meta.author;
    const text = file
      ? fs.readFileSync(path.join(dir, file), 'utf8').trim()
      : `The package ships no licence file; its package.json declares ${meta.license}` +
        (author ? `, author ${author}.` : '.');
    return `${meta.name} ${meta.version} (${meta.license})\n\n${text}`;
  });
  const head =
    'Third-party packages in src/nanodirt/js/strudel.js, besides Strudel itself\n' +
    '(AGPL-3.0-or-later, LICENSES/AGPL-3.0-or-later.txt). Generated by scripts/strudel_bundle/build.mjs.';
  const rule = '\n\n' + '-'.repeat(78) + '\n\n';
  fs.writeFileSync(notices, head + rule + sections.join(rule) + '\n');
  console.log(`${sections.length} third-party licences in`, notices);
}
